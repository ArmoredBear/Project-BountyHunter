using System;
using Godot;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   DIALOGUE UI
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Controls the dialogue box UI, fetching its labels in _Ready.
	**  2 - Exposes methods to display the speaker name and the current dialogue text.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

public partial class DialogueUI : Control
{
	//!---------------------------------------------------------------------------------------------------------
	#region Variables
	//!---------------------------------------------------------------------------------------------------------

	private Label _nameLabel;
	private RichTextLabel _textLabel;

	#endregion
	//!---------------------------------------------------------------------------------------------------------

	//!---------------------------------------------------------------------------------------------------------
	#region Initialization and Processes
	//!---------------------------------------------------------------------------------------------------------

	public override void _Ready()
	{
		// Usamos % para obter nós únicos na cena, é uma boa prática!
		_nameLabel = GetNode<Label>("%NameLabel");
		_textLabel = GetNode<RichTextLabel>("%TextLabel");
	}

	#endregion
	//!---------------------------------------------------------------------------------------------------------

	//!---------------------------------------------------------------------------------------------------------
	#region Methods and Interfaces
	//!---------------------------------------------------------------------------------------------------------

	public void SetDialogueName(string name)
	{
		_nameLabel.Text = name;
	}

	public void SetDialogueText(string text)
	{
		_textLabel.Text = text;
	}

    public static implicit operator DialogueUI(PackedScene v)
    {
        throw new NotImplementedException();
    }

	#endregion
	//!---------------------------------------------------------------------------------------------------------
}
