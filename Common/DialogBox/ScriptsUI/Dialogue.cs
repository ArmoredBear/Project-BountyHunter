using System.Collections.Generic;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   DIALOGUE LINE
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Represents a single dialogue line, holding the speaker name and the spoken text.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

// Representa uma única linha de diálogo no JSON.
public class DialogueLine
{
	//!---------------------------------------------------------------------------------------------------------
	#region Properties
	//!---------------------------------------------------------------------------------------------------------

	public string Character { get; set; }
	public string Text { get; set; }

	#endregion
	//!---------------------------------------------------------------------------------------------------------
}

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   DIALOGUE
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Represents the entire dialogue JSON file as a list of dialogue lines.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

// Representa o arquivo JSON inteiro, que contém uma lista de linhas.
public class Dialogue
{
	//!---------------------------------------------------------------------------------------------------------
	#region Properties
	//!---------------------------------------------------------------------------------------------------------

	public List<DialogueLine> Lines { get; set; }

	#endregion
	//!---------------------------------------------------------------------------------------------------------
}
