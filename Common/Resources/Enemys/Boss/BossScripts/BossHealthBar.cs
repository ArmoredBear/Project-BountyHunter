using Godot;
using System;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   BOSSHEALTHBAR
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Displays the boss health as a TextureProgressBar.
	**  2 - Updates the bar's Value each frame from the BossStats node's CurrentHealth.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

public partial class BossHealthBar : TextureProgressBar
{
    //!---------------------------------------------------------------------------------------------------------
    #region Methods
    //!---------------------------------------------------------------------------------------------------------

    public override void _Process(double delta)
    {
        base._Process(delta);
        Value = GetNode<EnemyStats>("%BossStats").CurrentHealth;
    }

    #endregion
    //!---------------------------------------------------------------------------------------------------------
}
