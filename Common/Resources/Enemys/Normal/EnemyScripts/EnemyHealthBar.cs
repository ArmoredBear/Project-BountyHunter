using Godot;
using System;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   ENEMYHEALTHBAR
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Displays the enemy health as a TextureProgressBar.
	**  2 - Updates the bar's Value each frame from the EnemyStats node's CurrentHealth.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

public partial class EnemyHealthBar : TextureProgressBar
{
    //!---------------------------------------------------------------------------------------------------------
    #region Methods
    //!---------------------------------------------------------------------------------------------------------

    public override void _Process(double delta)
    {
        base._Process(delta);
        Value = GetNode<EnemyStats>("%EnemyStats").CurrentHealth;
    }

    #endregion
    //!---------------------------------------------------------------------------------------------------------
}
