using Godot;
using System;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   MAINMENU
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Main menu overlay displayed over the game scene.
	**  2 - Shows/hides the menu panel and references it when null.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

public partial class MainMenu : CanvasLayer
{
    //!---------------------------------------------------------------------------------------------------------
    #region Properties
    //!---------------------------------------------------------------------------------------------------------

    [Export] public Panel Menu_Panel { get; set; }

    [Export] public bool Menu_is_Shown { get; set; } = false;

    #endregion
    //!---------------------------------------------------------------------------------------------------------

    //!---------------------------------------------------------------------------------------------------------
    #region Initialization and Processes
    //!---------------------------------------------------------------------------------------------------------

    public override void _Ready()
    {
        base._Ready();
        Reference_If_Null();

    }

    public override void _Process(double delta)
    {
        base._Process(delta);

        if (!Menu_is_Shown)
        {
            if (Input.IsAnythingPressed())
            {

                Menu_is_Shown = true;
            }
        }
    }

    #endregion
    //!---------------------------------------------------------------------------------------------------------

    //!---------------------------------------------------------------------------------------------------------
    #region Methods
    //!---------------------------------------------------------------------------------------------------------

    public void Reference_If_Null()
    {
        if (Menu_Panel == null)
        {
            GD.Print("Menu Panel is NULL!! Trying to reference it..");
            try
            {
                Menu_Panel = GetNode<Panel>("%MenuPanel");
                GD.Print("Sucess! Reference is: " + Menu_Panel.Name);
            }
            catch (Exception ex)
            {
                GD.Print(ex.Message);

            }
        }
    }

    #endregion
    //!---------------------------------------------------------------------------------------------------------

}
