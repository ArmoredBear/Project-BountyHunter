using Godot;
using System;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   GAMEMANAGER
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Holds the singleton instance of the Game Manager.
	**  2 - Validates that only one instance exists and reports a duplicate.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

public partial class GameManager : Node
{
    //!---------------------------------------------------------------------------------------------------------
    #region Variables
    //!---------------------------------------------------------------------------------------------------------

    public static GameManager Instance;

    #endregion
    //!---------------------------------------------------------------------------------------------------------

    //!---------------------------------------------------------------------------------------------------------
    #region Methods
    //!---------------------------------------------------------------------------------------------------------

    public override void _Ready()
    {
        base._Ready();

        if (Instance == null)
        {
            Instance = this;
            
        }

        else if (Instance != null && Instance != this)
        {
            GD.PrintErr("ERROR!! Instance of Game Manager already exist!!");
        }
        
        GD.Print("Game Manager loaded...");
        
    }

    #endregion
    //!---------------------------------------------------------------------------------------------------------
}
