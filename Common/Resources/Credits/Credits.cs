using Godot;
using System;

/**-----------------------------------------------------------------------------------------------------------------------
*!                                                   CREDITS
*-----------------------------------------------------------------------------------------------------------------------**/

/**-----------------------------------------------------------------------------------------------------------------------
	**                                                   PURPOSE
	*  
	**  1 - Credits button that toggles the visibility of the credits panel.
	*
*-----------------------------------------------------------------------------------------------------------------------**/

public partial class Credits : Button
{
    //!---------------------------------------------------------------------------------------------------------
    #region Variables
    //!---------------------------------------------------------------------------------------------------------

    [Export] public Panel Credits_Panel;

    #endregion
    //!---------------------------------------------------------------------------------------------------------

    //!---------------------------------------------------------------------------------------------------------
    #region Methods
    //!---------------------------------------------------------------------------------------------------------

    public void OnButtonPressed()
    {
        if (!Credits_Panel.Visible)
        {
            Credits_Panel.Visible = true;
        }

        else
        {
            Credits_Panel.Visible = false;
        }
    }

    #endregion
    //!---------------------------------------------------------------------------------------------------------
}
